# Writes the tables src/vm/native_methods/double_byte.rs reads, one file per
# encoding, from the Ruby running the script: the character each two-byte
# run stands for, and the bytes the encoding spells each of those characters
# with. GB18030 also gets the runs of its four-byte sequences below U+10000
# that stand for consecutive characters. Run it with the MRI release metorex
# follows.
#
#   ruby scripts/generate_double_byte_tables.rb

root = File.expand_path("..", __dir__)

ENCODINGS = {
  "GBK" => { file: "gbk_table.rs", prefix: "GBK", leads: 0x81..0xfe,
             trails: (0x40..0x7e).to_a + (0x80..0xfe).to_a, singles: [0x80] },
  "CP949" => { file: "cp949_table.rs", prefix: "CP949", leads: 0x81..0xfe,
               trails: (0x41..0x5a).to_a + (0x61..0x7a).to_a + (0x81..0xfe).to_a, singles: [] },
  "EUC-KR" => { file: "euc_kr_table.rs", prefix: "EUC_KR", leads: 0xa1..0xfe,
                trails: (0xa1..0xfe).to_a, singles: [] },
  "GB18030" => { file: "gb18030_table.rs", prefix: "GB18030", leads: 0x81..0xfe,
                 trails: (0x40..0x7e).to_a + (0x80..0xfe).to_a, singles: [], four_bytes: true },
}

# The four bytes GB18030 spells the sequence numbered `index` with, counting
# from 81 30 81 30.
def four_bytes(index)
  fourth = index % 10
  rest = index / 10
  third = rest % 126
  rest /= 126
  [0x81 + rest / 10, 0x30 + rest % 10, 0x81 + third, 0x30 + fourth]
end

# Runs of four-byte sequences below 84 31 A5 30, which stand for the
# characters of the Basic Multilingual Plane GB18030 spells with four bytes:
# where each starts, the character it starts with, and how long it is.
def four_byte_runs(encoding)
  runs = []
  (0...39420).each do |index|
    text = four_bytes(index).pack("C*").force_encoding(encoding)
    point = text.encode("UTF-8").ord
    last = runs.last
    if last && last[0] + last[2] == index && last[1] + last[2] == point
      last[2] += 1
    else
      runs << [index, point, 1]
    end
  rescue Encoding::UndefinedConversionError
    next
  end
  points = runs.map { |_, point, _| point }
  raise "four-byte runs are not in code point order" unless points == points.sort
  runs
end

ENCODINGS.each do |name, spec|
  encoding = Encoding.find(name)
  decoded = []
  spec[:leads].each do |lead|
    spec[:trails].each do |trail|
      text = [lead, trail].pack("C*").force_encoding(encoding)
      decoded << [(lead << 8) | trail, text.encode("UTF-8").ord]
    rescue Encoding::UndefinedConversionError, Encoding::InvalidByteSequenceError
      next
    end
  end

  single = spec[:singles].filter_map do |byte|
    [byte, byte.chr.force_encoding(encoding).encode("UTF-8").ord]
  rescue Encoding::UndefinedConversionError, Encoding::InvalidByteSequenceError
    nil
  end

  encoded = (decoded + single).map { |_, point| point }.uniq.sort.filter_map do |point|
    bytes = [point].pack("U").encode(encoding).bytes
    next if bytes.length > 2
    [point, bytes.inject(0) { |packed, byte| (packed << 8) | byte }]
  end

  lines = []
  lines << "//! The characters #{name} spells, generated by scripts/generate_double_byte_tables.rb"
  lines << "//! from Ruby #{RUBY_VERSION}. Do not edit. ASCII spells itself and is left out."
  lines << ""
  lines << "/// Each run of #{name} bytes that stands for a character, packed into one"
  lines << "/// number most significant byte first, with the code point it stands for,"
  lines << "/// sorted by the bytes."
  lines << "pub(crate) static #{spec[:prefix]}_DECODED: &[(u32, u32)] = &["
  (single + decoded).sort.each { |bytes, point| lines << format("    (0x%04X, 0x%05X),", bytes, point) }
  lines << "];"
  lines << ""
  lines << "/// Each character #{name} has bytes for, with those bytes packed into one"
  lines << "/// number, sorted by code point."
  lines << "pub(crate) static #{spec[:prefix]}_ENCODED: &[(u32, u32)] = &["
  encoded.each { |point, bytes| lines << format("    (0x%05X, 0x%04X),", point, bytes) }
  lines << "];"
  if spec[:four_bytes]
    lines << ""
    lines << "/// Runs of four-byte sequences that stand for consecutive characters: the"
    lines << "/// number of the sequence each starts at, counting from 81 30 81 30, the"
    lines << "/// code point it stands for, and how many sequences the run holds."
    lines << "pub(crate) static #{spec[:prefix]}_FOUR_BYTE_RUNS: &[(u32, u32, u32)] = &["
    four_byte_runs(encoding).each { |run| lines << format("    (%d, 0x%04X, %d),", *run) }
    lines << "];"
  end

  File.write(File.join(root, "src", "vm", "native_methods", spec[:file]), lines.join("\n") + "\n")
end
