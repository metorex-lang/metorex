# Writes src/vm/native_methods/native_arities.rs from the Ruby running this
# script: the arity MRI gives each core method it writes in C, for the classes
# and modules defined at startup. Metorex answers those methods natively, and
# `Method#arity` and `Method#parameters` for one read this table, so a matcher
# or a verifying double sees the signature MRI reports.
#
#   ruby scripts/generate_native_arities.rb
#
# Run it with the Ruby release metorex reports itself as.

root = File.expand_path("..", __dir__)

# Every class and module reachable by its own name, which leaves out
# anonymous ones and the ones such as ARGF.class that name no constant.
modules = ObjectSpace.each_object(Module).select do |mod|
  name = mod.name
  next false unless name && name.match?(/\A[A-Z]\w*(::[A-Z]\w*)*\z/)

  begin
    Object.const_get(name).equal?(mod)
  rescue NameError
    false
  end
end

def c_method?(method)
  method.source_location.nil?
end

instance_rows = {}
singleton_rows = {}

modules.each do |mod|
  (mod.public_instance_methods(false) + mod.private_instance_methods(false) + mod.protected_instance_methods(false)).each do |name|
    method = mod.instance_method(name)
    next unless method.owner.equal?(mod) && c_method?(method)

    instance_rows[[mod.name, name.to_s]] = method.arity
  end
  (mod.singleton_methods(false)).each do |name|
    method = mod.method(name)
    next unless c_method?(method)

    singleton_rows[[mod.name, name.to_s]] = method.arity
  end
end

def rows_source(rows)
  rows.sort.map do |(owner, name), arity|
    "    (#{owner.inspect}, #{name.inspect}, #{arity}),"
  end.join("\n")
end

source = <<~RUST
  // Generated by scripts/generate_native_arities.rb from Ruby #{RUBY_VERSION}.
  // Do not edit; run the script again instead.

  //! The arity MRI gives each core method it writes in C, by the class or
  //! module that defines it.

  /// Instance methods: owner, method name, arity.
  pub(crate) const INSTANCE_ARITIES: &[(&str, &str, i8)] = &[
  #{rows_source(instance_rows)}
  ];

  /// Methods a class or module answers itself: owner, method name, arity.
  pub(crate) const SINGLETON_ARITIES: &[(&str, &str, i8)] = &[
  #{rows_source(singleton_rows)}
  ];
RUST

path = File.join(root, "src/vm/native_methods/native_arities.rs")
File.write(path, source)
puts "wrote #{path}: #{instance_rows.size} instance and #{singleton_rows.size} singleton methods"
