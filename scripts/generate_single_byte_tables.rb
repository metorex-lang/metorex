# Writes src/vm/native_methods/string_methods/single_byte_tables.rs from the
# Ruby running the script: for each single-byte encoding that keeps ASCII
# and transcodes to UTF-8, the character each of its 256 bytes stands for,
# or none for a byte the encoding leaves undefined. Run it with the MRI
# release metorex follows.
#
#   ruby scripts/generate_single_byte_tables.rb

root = File.expand_path("..", __dir__)

single_byte = Encoding.list.select do |encoding|
  encoding.ascii_compatible? && !encoding.dummy? && encoding != Encoding::BINARY &&
    (0..255).all? do |byte|
      held = byte.chr.force_encoding(encoding)
      held.valid_encoding? && held.length == 1
    end
end

tables = single_byte.filter_map do |encoding|
  points = (0..255).map do |byte|
    byte.chr.force_encoding(encoding).encode("UTF-8").ord
  rescue Encoding::UndefinedConversionError
    nil
  rescue Encoding::ConverterNotFoundError
    break nil
  end
  [encoding.name, points] unless points.nil?
end

lines = []
lines << "// What each byte of the single-byte encodings of Ruby #{RUBY_VERSION} stands for,"
lines << "// generated by scripts/generate_single_byte_tables.rb. Do not edit."
lines << ""
lines << "/// A byte the encoding leaves without a character."
lines << "pub(crate) const UNDEFINED: u32 = u32::MAX;"
lines << ""
lines << "/// Each encoding's name, with the code point each of its bytes stands for."
lines << "pub(crate) const SINGLE_BYTE_TABLES: &[(&str, [u32; 256])] = &["
tables.each do |name, points|
  lines << "    ("
  lines << "        #{name.inspect},"
  lines << "        ["
  points.each_slice(8) do |row|
    lines << "            #{row.map { |point| point.nil? ? "UNDEFINED" : format("0x%04x", point) }.join(", ")},"
  end
  lines << "        ],"
  lines << "    ),"
end
lines << "];"

File.write(File.join(root, "src", "vm", "native_methods", "string_methods", "single_byte_tables.rs"), lines.join("\n") + "\n")
puts "#{tables.size} encodings"
