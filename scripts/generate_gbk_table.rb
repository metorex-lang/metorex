# Writes src/vm/native_methods/gbk_table.rs from the Ruby running the
# script: the character each two-byte GBK run stands for, and the bytes GBK
# spells each of those characters with. Run it with the MRI release metorex
# follows.
#
#   ruby scripts/generate_gbk_table.rb

root = File.expand_path("..", __dir__)

trails = (0x40..0x7e).to_a + (0x80..0xfe).to_a
decoded = []
(0x81..0xfe).each do |lead|
  trails.each do |trail|
    text = [lead, trail].pack("C*").force_encoding(Encoding::GBK)
    point = text.encode("UTF-8").ord
    decoded << [(lead << 8) | trail, point]
  rescue Encoding::UndefinedConversionError
    next
  end
end

single = (0x80..0x80).filter_map do |byte|
  [byte, byte.chr.force_encoding(Encoding::GBK).encode("UTF-8").ord]
rescue Encoding::UndefinedConversionError
  nil
end

encoded = (decoded + single).map { |_, point| point }.uniq.sort.map do |point|
  bytes = [point].pack("U").encode(Encoding::GBK).bytes
  [point, bytes.inject(0) { |packed, byte| (packed << 8) | byte }]
end

lines = []
lines << "//! The characters GBK spells, generated by scripts/generate_gbk_table.rb"
lines << "//! from Ruby #{RUBY_VERSION}. Do not edit. ASCII spells itself and is left out."
lines << ""
lines << "/// Each run of GBK bytes that stands for a character, packed into one"
lines << "/// number most significant byte first, with the code point it stands for,"
lines << "/// sorted by the bytes."
lines << "pub(crate) static GBK_DECODED: &[(u32, u32)] = &["
(single + decoded).sort.each { |bytes, point| lines << format("    (0x%04X, 0x%05X),", bytes, point) }
lines << "];"
lines << ""
lines << "/// Each character GBK has bytes for, with those bytes packed into one"
lines << "/// number, sorted by code point."
lines << "pub(crate) static GBK_ENCODED: &[(u32, u32)] = &["
encoded.each { |point, bytes| lines << format("    (0x%05X, 0x%04X),", point, bytes) }
lines << "];"

File.write(File.join(root, "src", "vm", "native_methods", "gbk_table.rs"), lines.join("\n") + "\n")
