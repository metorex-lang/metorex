# ExtensionFactory builds extendedKeyUsage and nsComment from their text.
require "openssl"
factory = OpenSSL::X509::ExtensionFactory.new
purposes = factory.create_extension("extendedKeyUsage", "serverAuth, clientAuth")
p purposes.to_a
p purposes.to_der.unpack1("H*")
comment = factory.create_extension("nsComment", "Generated by Ruby/OpenSSL")
p comment.to_a
p comment.to_der.unpack1("H*")
p((factory.create_extension("extendedKeyUsage", "noSuchPurpose") rescue $!.class))
